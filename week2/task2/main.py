zahl = 10
print("Integer:", zahl)
print("Type:", type(zahl))

kommazahl = 10.5
print("Floating point number:", kommazahl)
print("Type:", type(kommazahl))

text = "Hello, World!"
print("String:", text)
print("Type:", type(text))

wahrheitswert = True
print("Boolean:", wahrheitswert)
print("Type:", type(wahrheitswert))